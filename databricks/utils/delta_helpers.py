def assert_silver_schema(df: DataFrame) -> None:
    """
    Verify that the silver-layer DataFrame contains the fields required
    by the gold aggregation process.

    Raises ValueError when one or more required columns are absent.
    """

    required_columns = {
        "id",
        "category",
        "publishedAt",
        "nlpStatus",
        "sentiment",
        "entities",
        "keyPhrases",
    }

    available_columns = set(df.columns)
    missing_columns = required_columns - available_columns

    if missing_columns:
        raise ValueError(
            "Silver DataFrame is missing required columns: "
            f"{sorted(missing_columns)}. "
            f"Available columns: {sorted(available_columns)}"
        )

    print(
        f"  Silver schema check passed - "
        f"{len(available_columns)} columns available"
    )


def log_data_quality(
    df: DataFrame,
    label: str,
) -> None:
    """
    Print a compact quality summary for a DataFrame.

    Reports total rows, successful NLP rows, failed NLP rows,
    and PII rows when the hasPii column is available.
    """

    total_rows = df.count()

    successful_nlp = (
        df.filter(F.col("nlpStatus") == "ok")
        .count()
    )

    failed_nlp = total_rows - successful_nlp

    if "hasPii" in df.columns:
        pii_rows = (
            df.filter(F.col("hasPii") == True)
            .count()
        )
    else:
        pii_rows = "N/A"

    print(
        f"  [{label}] "
        f"rows={total_rows} "
        f"nlpOk={successful_nlp} "
        f"nlpFailed={failed_nlp} "
        f"pii={pii_rows}"
    )

    if total_rows == 0:
        print(
            f"  WARNING: [{label}] DataFrame contains no rows"
        )

    elif failed_nlp / max(total_rows, 1) > 0.20:
        print(
            f"  WARNING: [{label}] NLP failure rate exceeds 20% - "
            "check fn-enrich logs"
        )


def safe_explode_entities(df: DataFrame) -> DataFrame:
    """
    Expand the entities array into individual rows.

    The function supports both entity representations used by the
    pipeline:

      1. Structured entities from Azure Language:
         {text, category, confidenceScore}

      2. Simple string entities, such as those flattened for Search.

    The resulting DataFrame contains:
        id
        category
        entity_text
    """

    entity_schema = df.schema["entities"].dataType

    # Detect whether each entity is represented as a StructType.
    has_struct_entities = (
        hasattr(entity_schema, "elementType")
        and hasattr(entity_schema.elementType, "fields")
        and "text" in [
            field.name
            for field in entity_schema.elementType.fields
        ]
    )

    exploded_entities = (
        df.filter(F.col("entities").isNotNull())
        .select(
            "id",
            "category",
            F.explode("entities").alias("entity"),
        )
    )

    if has_struct_entities:
        return exploded_entities.withColumn(
            "entity_text",
            F.when(
                F.col("entity.text").isNotNull(),
                F.col("entity.text"),
            ).otherwise(
                F.col("entity").cast(StringType())
            ),
        )

    return exploded_entities.withColumn(
        "entity_text",
        F.col("entity").cast(StringType()),
    )