def merge_into_delta(
    spark: SparkSession,
    source_df: DataFrame,
    target_path: str,
    merge_keys: list,
    update_cols: list = None,
) -> dict:
    """
    Upsert records from source_df into a Delta table.

    A new Delta table is created when the target path does not exist.
    Otherwise, records are matched using merge_keys.

    Matched rows:
        Updated using update_cols, or all non-key columns when
        update_cols is not supplied.

    Unmatched rows:
        Inserted into the target table.

    Returns:
        Dictionary containing inserted, updated, and total row counts.
    """

    from delta.tables import DeltaTable

    # No existing Delta table: create it from the incoming data.
    if not DeltaTable.isDeltaTable(spark, target_path):
        (
            source_df.write
            .format("delta")
            .mode("overwrite")
            .save(target_path)
        )

        row_count = source_df.count()

        print(
            f"  Created Delta table: {target_path} "
            f"({row_count} rows)"
        )

        return {
            "inserted": row_count,
            "updated": 0,
            "total": row_count,
        }

    target_delta = DeltaTable.forPath(spark, target_path)

    # Construct the MERGE ON expression from the supplied key columns.
    join_expression = " AND ".join(
        f"target.{column} = source.{column}"
        for column in merge_keys
    )

    # When update columns are not specified, update every non-key field.
    columns_to_update = update_cols or [
        column
        for column in source_df.columns
        if column not in merge_keys
    ]

    update_values = {
        column: f"source.{column}"
        for column in columns_to_update
    }

    # Insert mapping contains every source column.
    insert_values = {
        column: f"source.{column}"
        for column in source_df.columns
    }

    (
        target_delta.alias("target")
        .merge(
            source_df.alias("source"),
            join_expression,
        )
        .whenMatchedUpdate(set=update_values)
        .whenNotMatchedInsert(values=insert_values)
        .execute()
    )

    # Read the metrics generated by the latest Delta operation.
    latest_metrics = (
        target_delta
        .history(1)
        .select("operationMetrics")
        .collect()[0][0]
    )

    rows_inserted = int(
        latest_metrics.get("numTargetRowsInserted", 0)
    )

    rows_updated = int(
        latest_metrics.get("numTargetRowsUpdated", 0)
    )

    print(
        f"  MERGE finished: {rows_inserted} inserted, "
        f"{rows_updated} updated -> {target_path}"
    )

    return {
        "inserted": rows_inserted,
        "updated": rows_updated,
        "total": rows_inserted + rows_updated,
    }


def overwrite_partition(
    df: DataFrame,
    target_path: str,
    partition_col: str,
    partition_value: str,
) -> int:
    """
    Replace one partition of a Delta table.

    REPLACE WHERE makes the operation idempotent: running the same
    partition again replaces that partition instead of creating
    duplicate records.

    Returns the number of rows written.
    """

    rows_to_write = df.count()

    (
        df.write
        .format("delta")
        .mode("overwrite")
        .option(
            "replaceWhere",
            f"{partition_col} = '{partition_value}'",
        )
        .save(target_path)
    )

    print(
        f"  Replaced {partition_col}={partition_value}: "
        f"{rows_to_write} rows -> {target_path}"
    )

    return rows_to_write


