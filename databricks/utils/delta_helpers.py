def rolling_window_filter(
    df: DataFrame,
    date_col: str,
    run_date: date,
    window_days: int,
) -> DataFrame:
    """
    Select records belonging to the current rolling window.

    The run_date is included as the final day of the window.

    For example, with a seven-day window ending on 2024-01-15,
    the selected dates are 2024-01-09 through 2024-01-15.
    """

    start_date = (
        run_date - timedelta(days=window_days - 1)
    ).isoformat()

    end_date = run_date.isoformat()

    return df.filter(
        (F.col(date_col) >= start_date)
        & (F.col(date_col) <= end_date)
    )


def prior_window_filter(
    df: DataFrame,
    date_col: str,
    run_date: date,
    window_days: int,
) -> DataFrame:
    """
    Select the period immediately preceding the current rolling window.

    This is used when calculating trend values by comparing the current
    window with the previous window.
    """

    previous_end = (
        run_date - timedelta(days=window_days)
    ).isoformat()

    previous_start = (
        run_date - timedelta(days=(window_days * 2 - 1))
    ).isoformat()

    return df.filter(
        (F.col(date_col) >= previous_start)
        & (F.col(date_col) <= previous_end)
    )


